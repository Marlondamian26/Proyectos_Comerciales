/**
 * Devuelve una imagen aleatoria de una categoría.
 */
export function getImagen(categoria: keyof typeof IMAGENES): string {
  const value = IMAGENES[categoria];
  if (Array.isArray(value)) {
    return value[Math.floor(Math.random() * value.length)];
  }
  // Si es un objeto con subcategorías, usar la primera subcategoría
  const subcategorias = Object.values(value);
  const primera = subcategorias[0];
  return Array.isArray(primera) ? primera[0] : primera;
}

/**
 * Devuelve una imagen específica de una subcategoría.
 */
export function getImagenDe(subcategoria: any): string {
  if (Array.isArray(subcategoria)) {
    return subcategoria[Math.floor(Math.random() * subcategoria.length)];
  }
  return subcategoria;
}
